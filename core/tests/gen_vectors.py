"""Turns the reference model's vectors (tests/vectors/lmsr_*.json, written by the reference model)
into Rust constants, so the core crate can be tested with no dependencies.  python3 tests/gen_vectors.py"""
import glob, json, os
here = os.path.dirname(os.path.abspath(__file__))
out = ["// Generated by tests/gen_vectors.py from tests/vectors/lmsr_*.json. Do not edit.", "",
       "pub struct Trade { pub sell: bool, pub who: usize, pub range: usize, pub yes: bool, pub tickets: u128, pub amount: u128, pub fee: u128, pub after: &'static [u128] }",
       "pub struct Vector { pub name: &'static str, pub depth: u128, pub fund: u128, pub fee_rate: u128, pub prices: &'static [u128], pub traders: usize, pub trades: &'static [Trade], pub pot: u128, pub revenue: u128, pub winning: &'static [u128], pub payouts: &'static [u128] }", ""]
names = []
for path in sorted(glob.glob(os.path.join(here, "vectors", "lmsr_*.json"))):
    v = json.load(open(path)); name = os.path.basename(path)[:-5]; names.append(name)
    arr = lambda xs: "&[" + ", ".join(f"{x}" for x in xs) + "]"
    trades = []
    for k in range(len(v["kinds"])):
        trades.append(f"Trade {{ sell: {str(v['kinds'][k] == 's').lower()}, who: {v['who'][k]}, range: {v['ranges'][k]}, yes: {str(v['sides'][k] == '1').lower()}, "
                      f"tickets: {v['tickets'][k]}, amount: {v['amounts'][k]}, fee: {v['fees'][k]}, after: {arr(v['after'][k])} }}")
    out.append(f"pub const {name.upper()}: Vector = Vector {{ name: \"{name}\", depth: {v['depth']}, fund: {v['fund']}, fee_rate: {v['feeRate']}, "
               f"prices: {arr(v['prices'])}, traders: {v['traders']}, trades: &[\n    " + ",\n    ".join(trades) + "\n], "
               f"pot: {v['pot']}, revenue: {v['revenue']}, winning: {arr(v['winning'])}, payouts: {arr(v['payouts'])} }};")
out.append("pub const ALL: &[&Vector] = &[" + ", ".join("&" + n.upper() for n in names) + "];")
open(os.path.join(here, "vectors_data.rs"), "w").write("\n".join(out) + "\n")
print("wrote", names)
